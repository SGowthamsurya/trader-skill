#!/usr/bin/env python3
"""Readiness gate: may a real-market performance experiment run, and may its result be called valid?

Every check has a category, a status and a mandatory flag:

  PASS            the evidence the check needs is present and verified
  BLOCKED         evidence is missing or contradicts what the run needs
  UNRESOLVED      evidence that matters is not settled either way
  NOT_APPLICABLE  the check has nothing to test yet (a ledger before a run)

The classification is READY only if every mandatory check is PASS or
NOT_APPLICABLE. Anything else is BLOCKED, and the runner refuses to start a
real-market experiment. Non-mandatory checks are limitations: they are
reported with every result and never silently dropped.

The gate is not tuned to let a run through: a check passes on evidence, not
because a conservative fallback exists. A conservative fallback (an unknown
fee excluded from cash, a no-file day left unfilled) keeps the simulation
honest; it does not make the evidence complete.

Usage:
  python3 india/readiness.py              # print the report (exit 0 READY, 3 BLOCKED)
  python3 india/readiness.py --json
"""

import argparse
import hashlib
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

ROOT = os.path.dirname(HERE)
PROTOCOL = os.path.join(HERE, "protocol.json")
SCHEMA = "india-readiness/1"
STATUSES = ("PASS", "BLOCKED", "UNRESOLVED", "NOT_APPLICABLE")
CATEGORIES = ("data", "calendar", "universe", "identity-corporate", "distributions", "costs-taxes", "benchmark",
              "ledger", "execution", "reproducibility")
MARKET_CRITERIA = ("start", "complete", "presence", "liquidity", "affordable", "category")
EVIDENCE_CRITERIA = ("identity", "corporate", "distributions")


class ReadinessError(Exception):
    pass


class Check(object):
    def __init__(self, id, category, status, mandatory, detail):
        if status not in STATUSES:
            raise ReadinessError("unknown status %r" % status)
        if category not in CATEGORIES:
            raise ReadinessError("unknown category %r" % category)
        self.id, self.category, self.status, self.mandatory, self.detail = id, category, status, bool(mandatory), detail

    def to_dict(self):
        return {"id": self.id, "category": self.category, "status": self.status, "mandatory": self.mandatory,
                "detail": self.detail}


def classify(checks):
    """READY only if every mandatory check is PASS or NOT_APPLICABLE."""
    if not checks:
        return "BLOCKED"
    ok = all(c.status in ("PASS", "NOT_APPLICABLE") for c in checks if c.mandatory)
    return "READY" if ok else "BLOCKED"


class Report(object):
    def __init__(self, checks, context):
        ids = [c.id for c in checks]
        if len(set(ids)) != len(ids):
            raise ReadinessError("duplicate check ids")
        self.checks, self.context = list(checks), dict(context)
        self.classification = classify(self.checks)

    def blockers(self):
        return [c for c in self.checks if c.mandatory and c.status not in ("PASS", "NOT_APPLICABLE")]

    def body(self):
        return {"schema": SCHEMA, "classification": self.classification, "context": self.context,
                "checks": [c.to_dict() for c in self.checks]}

    def digest(self):
        """SHA-256 of the report body (no timestamps), so a run can name the gate it passed."""
        return hashlib.sha256(json.dumps(self.body(), sort_keys=True, separators=(",", ":")).encode()).hexdigest()

    def to_json(self):
        return json.dumps(dict(self.body(), digest=self.digest()), indent=2, sort_keys=True) + "\n"

    def markdown(self):
        c = self.context
        out = ["# Readiness report", "",
               "Generated by `python3 india/backtest.py readiness`; do not edit by hand.", "",
               "**Classification: %s**" % self.classification, ""]
        if self.classification != "READY":
            out += ["**BLOCKED - NO VALID PERFORMANCE RESULT.** The real-market runner refuses to start until "
                    "every mandatory check passes. Nothing below is a performance figure.", ""]
        out += ["- Protocol: `%s` (sha256 `%s`)" % (c.get("protocol"), c.get("protocol_sha256")),
                "- Venue: %s; evaluation window %s to %s" % (c.get("venue"), c.get("start"), c.get("end")),
                "- Phase: %s" % c.get("phase"),
                "- Git commit: `%s`%s" % (c.get("git_commit"), " (working tree dirty)" if c.get("git_dirty") else ""),
                "- Report digest: `%s`" % self.digest(), "",
                "Statuses: PASS (evidence present and verified), BLOCKED (missing or contradicting evidence), "
                "UNRESOLVED (not settled either way), NOT_APPLICABLE (nothing to test yet). Mandatory checks "
                "decide the classification; the others are limitations reported with any result.", ""]
        counts = {}
        for x in self.checks:
            counts[(x.mandatory, x.status)] = counts.get((x.mandatory, x.status), 0) + 1
        out += ["| | %s |" % " | ".join(STATUSES), "| --- |" + " --- |" * len(STATUSES)]
        for m in (True, False):
            out.append("| %s | %s |" % ("mandatory" if m else "limitation",
                                        " | ".join(str(counts.get((m, s), 0)) for s in STATUSES)))
        out.append("")
        for cat in CATEGORIES:
            rows = [x for x in self.checks if x.category == cat]
            if not rows:
                continue
            out += ["## %s" % cat, "", "| check | status | mandatory | detail |", "| --- | --- | --- | --- |"]
            for x in rows:
                out.append("| `%s` | %s | %s | %s |" % (x.id, x.status, "yes" if x.mandatory else "no",
                                                       str(x.detail).replace("|", "/").replace("\n", " ")))
            out.append("")
        return "\n".join(out)


# ---------------------------------------------------------------- inputs

def sha_file(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def load_protocol(path=PROTOCOL):
    with open(path, encoding="utf-8") as fh:
        p = json.load(fh)
    if p.get("schema") != "india-protocol/1":
        raise ReadinessError("%s is not a protocol" % path)
    return p


def git_state(repo=ROOT):
    """(commit or None, dirty or None). Ignored files (the local cache) do not count as dirty."""
    try:
        head = subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"], capture_output=True, text=True, timeout=30)
        st = subprocess.run(["git", "-C", repo, "status", "--porcelain"], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None, None
    if head.returncode or st.returncode:
        return None, None
    return head.stdout.strip(), bool(st.stdout.strip())


# ---------------------------------------------------------------- checks (pure: inputs in, Check out)

def check_protocol(protocol, here=HERE):
    bad = []
    for part in ("strategy", "criteria"):
        f = os.path.join(here, protocol[part]["file"])
        if not os.path.exists(f):
            bad.append("%s file %s is missing" % (part, protocol[part]["file"]))
        elif sha_file(f) != protocol[part]["sha256"]:
            bad.append("%s file %s does not match its frozen sha256" % (part, protocol[part]["file"]))
    if bad:
        return Check("protocol-frozen", "reproducibility", "BLOCKED", True, "; ".join(bad))
    return Check("protocol-frozen", "reproducibility", "PASS", True,
                 "strategy %s and criteria %s match the frozen sha256 in protocol.json"
                 % (protocol["strategy"]["sha256"][:12], protocol["criteria"]["sha256"][:12]))


def check_git(commit, dirty):
    if commit is None:
        return Check("git-clean", "reproducibility", "BLOCKED", True, "the git commit could not be read")
    if dirty:
        return Check("git-clean", "reproducibility", "BLOCKED", True,
                     "the working tree at %s has uncommitted changes; a run must name the exact code" % commit[:12])
    return Check("git-clean", "reproducibility", "PASS", True, "clean working tree at %s" % commit[:12])


def check_inventory(result, expected):
    """result: inventory.check output, or None if the cache is absent."""
    if result is None:
        return Check("cache-inventory", "data", "BLOCKED", True,
                     "no local cache; recover it with MANUAL_DOWNLOADS.md and check it against cache_inventory.json")
    miss, bad = len(result["missing"]), len(result["corrupt"])
    if miss or bad:
        return Check("cache-inventory", "data", "BLOCKED", True,
                     "%d of %d inventoried files missing, %d failing their checksum" % (miss, expected, bad))
    return Check("cache-inventory", "data", "PASS", True,
                 "all %d inventoried files present and matching their sha256" % expected)


def check_backup():
    return Check("off-container-backup", "reproducibility", "UNRESOLVED", False,
                 "the raw cache exists only in this container; no approved backup holds a verified copy. "
                 "cache_inventory.json (committed) names every file and checksum so a re-download can be verified")


def check_price_coverage(classes, start, end):
    """classes: bhav.classify output {weekday: class} over start..end (lookback included)."""
    if not classes:
        return Check("price-coverage", "data", "BLOCKED", True, "no weekday in %s..%s is classified" % (start, end))
    n = {}
    for c in classes.values():
        n[c] = n.get(c, 0) + 1
    bad = n.get("unresolved", 0) + n.get("invalid-undocumented", 0)
    gaps = sorted(d for d, c in classes.items() if c == "documented-gap")
    detail = "%s to %s: %d weekdays with a valid file, %d refused in every layout, %d documented gaps (%s), " \
             "%d unresolved" % (start, end, n.get("valid-file", 0), n.get("refused-all-layouts", 0), len(gaps),
                                ", ".join(gaps) or "none", bad)
    if bad:
        return Check("price-coverage", "data", "BLOCKED", True, detail)
    return Check("price-coverage", "data", "PASS", True, detail + "; documented gaps are excluded from signals "
                 "and fills and valued conservatively (Phase 2.2 decision)")


def check_provenance(provenance):
    if provenance is None:
        return Check("market-data-provenance", "data", "NOT_APPLICABLE", True,
                     "no market data loaded for this report; the runner checks it again before any run")
    if provenance != "exchange-cache":
        return Check("market-data-provenance", "data", "BLOCKED", True,
                     "market data provenance is %r: synthetic or hand-built data can never produce a real-market "
                     "result" % provenance)
    return Check("market-data-provenance", "data", "PASS", True, "loaded by pit.from_cache from verified files")


def check_official_calendar(official_dates, refused_days, start, end):
    """official_dates: dates with an official holiday or session record; refused_days: weekdays refused in every
    layout inside the window (closures that would otherwise be unconfirmed)."""
    years = range(int(start[:4]), int(end[:4]) + 1)
    have = sorted({d[:4] for d in official_dates})
    missing = [str(y) for y in years if str(y) not in have]
    unconfirmed = [d for d in refused_days if d not in set(official_dates)]
    detail = "official holiday lists imported for %s; missing for %s; %d weekday(s) in the window with no file " \
             "and no official record (closure unconfirmed)" % (", ".join(have) or "no year",
                                                               ", ".join(missing) or "none", len(unconfirmed))
    if missing or unconfirmed:
        return Check("official-calendar", "calendar", "BLOCKED", True, detail +
                     ". Without the official list a no-file weekday cannot be told apart from a missed session")
    return Check("official-calendar", "calendar", "PASS", True, detail)


def check_category_evidence(categories, start):
    """categories: {isin: [(category, knowable_from, source)]} as in universe.Evidence."""
    dates = sorted({k for facts in categories.values() for _, k, _ in facts})
    if not dates:
        return Check("category-evidence", "universe", "BLOCKED", True, "no fund-category evidence on record")
    early = [d for d in dates if d <= start]
    if not early:
        return Check("category-evidence", "universe", "BLOCKED", True,
                     "every fund-category fact is knowable only from %s (AMFI NAVAll.txt is undated, so it counts "
                     "from its retrieval), after the evaluation start %s; no ETF can pass the category test on any "
                     "decision date. Needed: dated scheme documents or a dated AMFI list on or before %s"
                     % (dates[0], start, start))
    return Check("category-evidence", "universe", "PASS", True,
                 "category facts knowable from %s, on or before the evaluation start %s" % (early[0], start))


def check_survivorship():
    return Check("survivorship", "universe", "PASS", True,
                 "the candidate list comes from every fund row in the daily files over the whole period, including "
                 "ETFs that stopped trading; each decision uses only rows up to that day. Limitation: an ETF never "
                 "seen in a BSE file is not a candidate")


def check_evidence_criteria(results):
    """results: etf.evaluate_all output. One check per evidence criterion, over the candidates whose market
    criteria (history, completeness, presence, liquidity, affordability, category) do not fail."""
    qualified = [r for r in results if all(r["criteria"].get(k, ("pass",))[0] != "fail" for k in MARKET_CRITERIA)]
    names = lambda rs: ", ".join(r["candidate"]["symbol"] for r in rs) or "none"
    out = []
    for crit, cat in (("identity", "identity-corporate"), ("corporate", "identity-corporate"),
                      ("distributions", "distributions")):
        ok = [r for r in qualified if r["criteria"].get(crit, ("unresolved",))[0] == "pass"]
        notok = [r for r in qualified if r not in ok]
        detail = "%d of %d market-qualified candidates pass (%s); not passing: %s" % (
            len(ok), len(qualified), names(ok), "; ".join("%s: %s" % (r["candidate"]["symbol"], r["criteria"].get(
                crit, ("unresolved", "no review"))[1]) for r in notok) or "none")
        out.append(Check(crit + "-evidence", cat, "PASS" if ok else "BLOCKED", True, detail))
    eligible = [r for r in results if r["verdict"] == "ELIGIBLE"]
    out.append(Check("eligible-candidates", "universe", "PASS" if eligible else "BLOCKED", True,
                     "%d candidate(s) pass every criterion over the whole period (%s); with none the strategy holds "
                     "cash throughout and the experiment measures nothing" % (len(eligible), names(eligible))))
    return out


def check_costs(gaps, start, end):
    """gaps: costs.Schedule.coverage output."""
    if gaps:
        return Check("cost-coverage", "costs-taxes", "BLOCKED", True,
                     "%d component/side pair(s) lack a verified rate over %s..%s: %s" % (
                         len(gaps), start, end, "; ".join("%s (%s)" % (c, s) for c, s, _ in gaps)))
    return Check("cost-coverage", "costs-taxes", "PASS", True, "every applicable component verified over the window")


def check_investor_taxes(items):
    return Check("investor-taxes", "costs-taxes", "UNRESOLVED", False,
                 "the protocol reports pre-tax results; investor-level items stay unresolved: %s"
                 % (", ".join(i.get("id", "?") for i in items) or "none listed"))


def check_tri(status, info, gaps=None):
    if status != "AVAILABLE":
        return Check("benchmark-tri", "benchmark", "BLOCKED", True, "NIFTY 50 TRI: %s" % info)
    if gaps:
        return Check("benchmark-tri", "benchmark", "BLOCKED", True, "NIFTY 50 TRI does not cover the window: "
                     + "; ".join(gaps))
    return Check("benchmark-tri", "benchmark", "PASS", True, "NIFTY 50 TRI %s to %s (%d rows)" % (
        info["first"], info["last"], info["rows"]))


def check_niftybees(results, cost_gaps):
    r = [x for x in results if x["candidate"]["symbol"] == "NIFTYBEES"]
    if not r:
        return Check("benchmark-niftybees", "benchmark", "BLOCKED", True, "NIFTYBEES is not a candidate on this venue")
    bad = ["%s: %s" % (k, r[0]["criteria"][k][1]) for k in EVIDENCE_CRITERIA
           if r[0]["criteria"].get(k, ("unresolved",))[0] != "pass"]
    if cost_gaps:
        bad.append("costs: %d component/side pair(s) unresolved" % len(cost_gaps))
    if bad:
        return Check("benchmark-niftybees", "benchmark", "BLOCKED", True,
                     "cost-matched NIFTYBEES buy-and-hold needs verified evidence; missing: " + "; ".join(bad))
    return Check("benchmark-niftybees", "benchmark", "PASS", True, "NIFTYBEES evidence and costs verified")


def check_cash_control():
    return Check("benchmark-cash", "benchmark", "PASS", False,
                 "uninvested cash returns zero by construction; a control, not a market benchmark")


def check_ledger(ledger_info):
    """ledger_info: None before a run, else {"sealed": bool, "anchor_matches": bool, "head": str}."""
    if ledger_info is None:
        return Check("ledger-sealed", "ledger", "NOT_APPLICABLE", True,
                     "no ledger yet; the runner seals one and reopens it only with the seal recorded outside it")
    if not ledger_info.get("sealed") or not ledger_info.get("anchor_matches"):
        return Check("ledger-sealed", "ledger", "BLOCKED", True, "the ledger is unsealed or its seal does not match "
                     "the external anchor")
    return Check("ledger-sealed", "ledger", "PASS", True, "sealed; head %s matches the anchor" % ledger_info["head"][:12])


def check_execution(protocol):
    ex = protocol.get("execution", {})
    out = []
    if ex.get("liquidity_cap") == "ex-ante":
        out.append(Check("liquidity-cap", "execution", "PASS", True,
                         "ex-ante: an order is placed only if it is at most 5% of the decision day's traded value"))
    else:
        out.append(Check("liquidity-cap", "execution", "BLOCKED", True,
                         "liquidity_cap %r uses information not known when the order is placed" % ex.get("liquidity_cap")))
    out.append(Check("price-limits", "execution", "UNRESOLVED", False,
                     "price bands, circuit limits, slippage from the open, queue position and partial fills are not "
                     "modelled; the daily files do not record them. Fills at the open are an assumption"))
    return out


# ---------------------------------------------------------------- assembly

def assess(cache, protocol_path=PROTOCOL, provenance=None, ledger_info=None, phase="pre-run", repo=ROOT,
           git=None):
    """The full report on the real cache and committed evidence. provenance: of the MarketData the runner loaded
    (None for a stand-alone report). git: (commit, dirty) to override the repository state (tests only)."""
    import bhav
    import costs
    import etf
    import inventory
    import tri
    import universe
    protocol = load_protocol(protocol_path)
    here = os.path.dirname(os.path.abspath(protocol_path))
    venue = protocol["venue"]
    start, end = protocol["windows"]["evaluation"]["start"], protocol["windows"]["evaluation"]["end"]
    dev_start = protocol["windows"]["development"]["start"]
    commit, dirty = git if git is not None else git_state(repo)
    checks = [check_protocol(protocol, here), check_git(commit, dirty), check_backup()]

    records = list(cache.records()) if os.path.isdir(cache.root) else []
    with open(inventory.INVENTORY, encoding="utf-8") as fh:
        inv = json.load(fh)
    checks.append(check_inventory(inventory.check(cache, inv) if records else None, inv["count"]))
    checks.append(check_provenance(provenance))
    if not records:
        checks.append(Check("price-coverage", "data", "BLOCKED", True, "no local cache"))
        report = Report(checks, _context(protocol, protocol_path, phase, commit, dirty))
        return report

    import datetime
    D = datetime.date.fromisoformat
    classes = bhav.classify(records, venue, D(dev_start), D(end))
    checks.append(check_price_coverage(classes, dev_start, end))

    import calendar_in
    official = []
    for r in records:
        if r.get("source") == calendar_in.OFFICIAL and r.get("exchange") == venue and r.get("ok"):
            official += [d.isoformat() for d, _, _ in calendar_in.parse_official(
                cache.read(r["sha256"]).decode("utf-8-sig"))]
    refused = sorted(d for d, c in classes.items() if c == "refused-all-layouts" and start <= d <= end)
    checks.append(check_official_calendar(official, refused, start, end))

    ev = universe.Evidence.from_files(cache)
    checks.append(check_category_evidence(ev.categories, start))
    checks.append(check_survivorship())
    crit = etf.read_json(os.path.join(here, protocol["criteria"]["file"]), "criteria")
    cands = etf.read_json(etf.CANDIDATES, "candidates")["candidates"]
    _, results = etf.evaluate_all(cache, crit, cands, etf.read_actions(etf.ACTIONS))
    checks += check_evidence_criteria(results)

    sched = costs.Schedule.load()
    gaps = sched.coverage(start, end, venue, "etf")
    checks.append(check_costs(gaps, start, end))
    checks.append(check_investor_taxes(costs.investor_taxes(sched)))

    st, info = tri.status(cache)
    tgaps = None
    if st == "AVAILABLE":
        tgaps = tri.coverage([d for d, _ in tri.load_series(cache)], start, end)
    checks.append(check_tri(st, info, tgaps))
    checks.append(check_niftybees(results, gaps))
    checks.append(check_cash_control())
    checks.append(check_ledger(ledger_info))
    checks += check_execution(protocol)
    return Report(checks, _context(protocol, protocol_path, phase, commit, dirty))


def _context(protocol, protocol_path, phase, commit, dirty):
    ev = protocol["windows"]["evaluation"]
    return {"protocol": os.path.basename(protocol_path), "protocol_sha256": sha_file(protocol_path),
            "venue": protocol["venue"], "start": ev["start"], "end": ev["end"], "phase": phase,
            "git_commit": commit, "git_dirty": dirty, "python": "%d.%d.%d" % sys.version_info[:3]}


def main(argv=None):
    import fetch
    ap = argparse.ArgumentParser(description="Readiness gate for a real-market India experiment.")
    ap.add_argument("--cache", default=fetch.DEFAULT_CACHE)
    ap.add_argument("--protocol", default=PROTOCOL)
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args(argv)
    rep = assess(fetch.Cache(a.cache), a.protocol)
    sys.stdout.write(rep.to_json() if a.json else rep.markdown() + "\n")
    return 0 if rep.classification == "READY" else 3


if __name__ == "__main__":
    sys.exit(main())
